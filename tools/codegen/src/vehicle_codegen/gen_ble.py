def _py_scalar(value: Any) -> str:
    if isinstance(value, str):
        return json.dumps(value)
    return repr(value)


def _py_literal(value: Any, indent: int = 0) -> str:
    """Deterministic Python literal: flat containers on one line, nested ones expanded."""
    pad = "    " * (indent + 1)
    if isinstance(value, dict):
        if not value:
            return "{}"
        flat = not any(isinstance(v, dict | list) for v in value.values())
        if flat:
            return (
                "{" + ", ".join(f"{json.dumps(k)}: {_py_scalar(v)}" for k, v in value.items()) + "}"
            )
        rows = [f"{pad}{json.dumps(k)}: {_py_literal(v, indent + 1)}," for k, v in value.items()]
        return "{\n" + "\n".join(rows) + "\n" + "    " * indent + "}"
    if isinstance(value, list):
        if not any(isinstance(v, dict | list) for v in value):
            return "[" + ", ".join(_py_scalar(v) for v in value) + "]"
        rows = [f"{pad}{_py_literal(v, indent + 1)}," for v in value]
        return "[\n" + "\n".join(rows) + "\n" + "    " * indent + "]"
    return _py_scalar(value)


