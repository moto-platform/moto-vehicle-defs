    pubspec = (
        "# GENERATED by vehicle-defs tools/codegen from ble/ble_schema.json. DO NOT EDIT.\n"
        "name: vehicle_defs\n"
        "description: BLE packet layout of vehicle-connectivity-node (D-061) and the vehicle "
        "signal catalog (D-066), generated from vehicle-defs.\n"
        "publish_to: none\n"
        "environment:\n"
        '  sdk: ">=3.0.0 <4.0.0"\n'
    )
    barrel = DART_BANNER + "\nexport 'ble_schema.dart';\nexport 'vehicle_signals.dart';\n"
    return {
        "pubspec.yaml": pubspec,
        "lib/ble_schema.dart": "\n".join(out).rstrip("\n") + "\n",
        "lib/vehicle_defs.dart": barrel,
    }


