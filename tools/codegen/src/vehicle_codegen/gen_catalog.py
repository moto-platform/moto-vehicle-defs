"""Vehicle signal catalog (D-066, D-078 item 2): polled DIDs + unpolled catalog entries.

`uds/obd_catalog.yaml` is a vehicle-independent catalog of the standard SAE J1979 mode 0x01
PIDs read over UDS 0x22 0xF4xx (scalar ones, and multi-value ones with `fields`, D-068) and
of the ISO 14229-1 identification DIDs. They are not polled: no C target gets this catalog.
It is merged with the polled DIDs of the vehicle's poll list (`uds/vehicle_cl250.yaml`) and
generated as Python (vehicle-server) and Dart (vehicle-mobile), so both can show every signal and
mark which ones flow. An entry becomes a polled DID only through /signal-change (D-059
item 4, D-066 item 3, D-078 item 2).
"""

from __future__ import annotations

import re
from typing import Any

from .yaml_checks import frame_allowed, request_allowed, single_frame

SOURCE = "uds/vehicle_cl250.yaml + uds/obd_catalog.yaml"
PY_BANNER = f'"""GENERATED by vehicle-defs tools/codegen from {SOURCE}. DO NOT EDIT."""\n'
DART_BANNER = (
    f"// GENERATED by vehicle-defs tools/codegen from {SOURCE}. DO NOT EDIT.\n"
    "// Regenerate with `make gen`.\n"
)

_NAME = re.compile(r"[A-Z][A-Z0-9_]*")
_LENGTHS = (1, 2, 4)
_BASE_REQUIRED = ("obd_pid", "did", "name", "label", "group", "length", "description")
# Scalar entry: one number, decoded with a formula. A multi-value entry has `fields` instead.
_SCALAR_KEYS = ("factor_num", "factor_den", "offset", "unit", "min", "max")
_REQUIRED = _BASE_REQUIRED + _SCALAR_KEYS
# Poll settings belong to the vehicle's poll list only: a catalog entry is never polled.
_POLL_KEYS = ("poll_period_ms", "stale_after_ms", "priority", "poll_period_verified")
_FIELD_REQUIRED = ("name", "byte", "factor_num", "factor_den", "offset", "unit", "min", "max")
_FIELD_OPTIONAL = ("size", "bit", "bits", "enum", "not_used_raw")
_FIELD_SIZES = (1, 2, 3, 4)
# ISO 14229-1 Annex C identification DIDs. 0xF18C (serial number) and 0xF190 (VIN) are
# personal data (D-033, D-059) and never listed.
_IDENT_REQUIRED = ("did", "name", "label", "description", "encoding")
_IDENT_RANGE = (0xF180, 0xF19F)
_IDENT_PERSONAL = (0xF18C, 0xF190)
STATUS_POLLED = "polled"
STATUS_CANDIDATE = "candidate"


def _is_int(value: Any) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _is_num(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _close(a: float, b: float) -> bool:
    return abs(a - b) <= 1e-9 * max(1.0, abs(a), abs(b))


def _check_formula(label: str, e: dict[str, Any], raw_max: int) -> list[str]:
    """factor_num/factor_den/offset are valid and min/max are raw 0 and raw_max through them."""
    num, den, off = e["factor_num"], e["factor_den"], e["offset"]
    if not (_is_int(num) and num > 0 and _is_int(den) and den > 0 and _is_num(off)):
        return [f"{label}: factor_num/factor_den must be positive integers, offset a number"]
    if not (_is_num(e["min"]) and _is_num(e["max"])):
        return [f"{label}: min/max must be numbers"]
    errors: list[str] = []
    if not _close(e["min"], off):
        errors.append(f"{label}: min {e['min']} != raw 0 through the formula ({off})")
    top = raw_max * num / den + off
    if not _close(e["max"], top):
        errors.append(f"{label}: max {e['max']} != raw {raw_max} through the formula ({top})")
    return errors


def _check_fields(label: str, e: dict[str, Any]) -> list[str]:
    """`fields` of a multi-value entry: inside `length`, no shared bit, formula and enum valid."""
    fields = e["fields"]
    if not (isinstance(fields, list) and fields):
        return [f"{label}: fields must be a non-empty list"]
    errors: list[str] = []
    for key in _SCALAR_KEYS:
        if key in e:
            errors.append(f"{label}: '{key}' not allowed next to fields (put it in each field)")
    used: set[int] = set()
    names: set[str] = set()
    for i, f in enumerate(fields):
        fl = f"{label} field[{i}] {f.get('name', '?') if isinstance(f, dict) else '?'}"
        if not isinstance(f, dict):
            errors.append(f"{fl}: must be a mapping")
            continue
        missing = [k for k in _FIELD_REQUIRED if k not in f]
        if missing:
            errors.append(f"{fl}: missing {', '.join(missing)}")
            continue
        unknown = sorted(set(f) - set(_FIELD_REQUIRED) - set(_FIELD_OPTIONAL))
        if unknown:
            errors.append(f"{fl}: unknown keys {unknown}")
        if not (isinstance(f["name"], str) and _NAME.fullmatch(f["name"])):
            errors.append(f"{fl}: name must be UPPER_SNAKE")
        elif f["name"] in names:
            errors.append(f"{fl}: name already used in this entry")
        names.add(f["name"])
        if not (isinstance(f["unit"], str)):
            errors.append(f'{fl}: unit must be a string ("" = raw)')
        byte = f["byte"]
        whole = "size" in f
        sub = "bit" in f or "bits" in f
        if whole == sub or (sub and not ("bit" in f and "bits" in f)):
            errors.append(f"{fl}: needs either size, or bit and bits")
            continue
        if whole:
            span, shift, width = f["size"], 0, 8 * f["size"] if _is_int(f["size"]) else 0
            if not (_is_int(span) and span in _FIELD_SIZES):
                errors.append(f"{fl}: size must be one of {_FIELD_SIZES}")
                continue
        else:
            span, shift, width = 1, f["bit"], f["bits"]
            if not (_is_int(shift) and _is_int(width) and shift >= 0 and width >= 1):
                errors.append(f"{fl}: bit must be >= 0 and bits >= 1")
                continue
            if shift + width > 8:
                errors.append(f"{fl}: bit {shift} + bits {width} leaves the byte")
                continue
        if not (_is_int(byte) and byte >= 0 and byte + span <= e["length"]):
            errors.append(f"{fl}: byte {byte} + {span} leaves length {e['length']}")
            continue
        bits = set(range(8 * byte + shift, 8 * byte + shift + width))
        if bits & used:
            errors.append(f"{fl}: shares a bit with an earlier field")
        used |= bits
        raw_max = (1 << width) - 1
        errors += _check_formula(fl, f, raw_max)
        if "enum" in f:
            enum = f["enum"]
            if not (isinstance(enum, dict) and enum):
                errors.append(f"{fl}: enum must be a non-empty mapping")
            else:
                if not all(_is_int(k) and 0 <= k <= raw_max for k in enum):
                    errors.append(f"{fl}: enum keys must be raw values in 0..{raw_max}")
                if not all(isinstance(v, str) and _NAME.fullmatch(v) for v in enum.values()):
                    errors.append(f"{fl}: enum names must be UPPER_SNAKE")
                if len(set(enum.values())) != len(enum):
                    errors.append(f"{fl}: enum names must be unique")
        if "not_used_raw" in f and not (
            _is_int(f["not_used_raw"]) and 0 <= f["not_used_raw"] <= raw_max
        ):
            errors.append(f"{fl}: not_used_raw must be a raw value in 0..{raw_max}")
    return errors


def _check_read(label: str, did: Any, vehicle: dict[str, Any]) -> list[str]:
    """The 0x22 read of `did` passes tester_policy and the frame gate (D-020)."""
    if not (_is_int(did) and 0 <= did <= 0xFFFF):
        return []
    payload = [0x22, did >> 8, did & 0xFF]
    if not request_allowed(vehicle["tester_policy"], payload):
        return [f"{label}: 0x22 read refused by tester_policy (D-020)"]
    if not frame_allowed(vehicle, single_frame(vehicle, payload)):
        return [f"{label}: 0x22 read refused by the frame gate (D-020)"]
    return []


def _check_entry(
    label: str, e: dict[str, Any], groups: set[str], vehicle: dict[str, Any]
) -> list[str]:
    errors: list[str] = []
    multi = "fields" in e
    required = _BASE_REQUIRED if multi else _REQUIRED
    missing = [k for k in required if k not in e]
    if missing:
        return [f"{label}: missing {', '.join(missing)}"]
    for key in _POLL_KEYS:
        if key in e:
            errors.append(f"{label}: '{key}' not allowed, a candidate is never polled (D-066)")
    pid, did = e["obd_pid"], e["did"]
    if not (_is_int(pid) and 0x00 < pid <= 0xFF) or pid % 0x20 == 0:
        errors.append(f"{label}: obd_pid must be a data PID in 0x01..0xFF, not a support PID")
    elif did != 0xF400 | pid:
        errors.append(f"{label}: did must be 0xF400 | obd_pid = 0x{0xF400 | pid:04X}")
    if not (isinstance(e["name"], str) and _NAME.fullmatch(e["name"])):
        errors.append(f"{label}: name must be UPPER_SNAKE")
    if not (isinstance(e["label"], str) and e["label"].strip()):
        errors.append(f"{label}: empty label")
    if e["group"] not in groups:
        errors.append(f"{label}: group '{e['group']}' not in groups")
    if e["length"] not in _LENGTHS:
        errors.append(f"{label}: length must be one of {_LENGTHS}")
    elif multi:
        errors += _check_fields(label, e)
    else:
        errors += _check_formula(label, e, (1 << (8 * e["length"])) - 1)
    if not multi and not (isinstance(e["unit"], str) and e["unit"]):
        errors.append(f"{label}: empty unit")
    return errors + _check_read(label, did, vehicle)


def _check_identification(
    items: Any, vehicle: dict[str, Any], names: set[str], dids: set[int]
) -> list[str]:
    if not isinstance(items, list):
        return ["identification: must be a list"]
    errors: list[str] = []
    for i, e in enumerate(items):
        label = f"identification[{i}] {e.get('name', '?')}"
        missing = [k for k in _IDENT_REQUIRED if k not in e]
        if missing:
            errors.append(f"{label}: missing {', '.join(missing)}")
            continue
        did = e["did"]
        if not _is_int(did):
            errors.append(f"{label}: did must be an integer")
        elif did in _IDENT_PERSONAL:
            errors.append(f"{label}: DID 0x{did:04X} is personal data, never listed (D-033, D-059)")
        elif not _IDENT_RANGE[0] <= did <= _IDENT_RANGE[1]:
            errors.append(
                f"{label}: did outside the ISO 14229-1 identification range "
                f"0x{_IDENT_RANGE[0]:04X}..0x{_IDENT_RANGE[1]:04X}"
            )
        if not (isinstance(e["name"], str) and _NAME.fullmatch(e["name"])):
            errors.append(f"{label}: name must be UPPER_SNAKE")
        if not (isinstance(e["label"], str) and e["label"].strip()):
            errors.append(f"{label}: empty label")
        if not (isinstance(e["description"], str) and e["description"].strip()):
            errors.append(f"{label}: empty description")
        if e["encoding"] != "ascii":
            errors.append(f"{label}: encoding must be ascii")
        if "length" in e:
            errors.append(f"{label}: 'length' not allowed, an identification DID is variable")
        for key in _POLL_KEYS:
            if key in e:
                errors.append(f"{label}: '{key}' not allowed, never polled")
        if e["name"] in names:
            errors.append(f"{label}: name already used")
        if did in dids:
            errors.append(f"{label}: DID 0x{did:04X} already listed")
        names.add(e["name"])
        dids.add(did)
        errors += _check_read(label, did, vehicle)
    return errors


def check_catalog(cand: dict[str, Any], vehicle: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    if cand.get("schema_version") != 1:
        errors.append("candidates: schema_version must be 1")
    groups = cand.get("groups")
    if not (isinstance(groups, list) and groups and len(set(groups)) == len(groups)):
        return errors + ["candidates: groups must be a non-empty list without duplicates"]
    gset = set(groups)
    polled_names = [d["name"] for d in vehicle["dids"]]
    polled_dids = {d["did"] for d in vehicle["dids"]}
    meta = cand.get("polled") or {}
    if set(meta) != set(polled_names):
        missing = sorted(set(polled_names) - set(meta))
        extra = sorted(set(meta) - set(polled_names))
        errors.append(
            "candidates: `polled` keys must equal the DID names of uds/vehicle_cl250.yaml "
            f"(missing {missing}, extra {extra})"
        )
    for name, m in meta.items():
        if (
            not isinstance(m, dict)
            or m.get("group") not in gset
            or not str(m.get("label", "")).strip()
        ):
            errors.append(f"candidates: polled {name} needs a known group and a label")
    names = set(polled_names)
    dids = set(polled_dids)
    for i, e in enumerate(cand.get("candidates") or []):
        label = f"candidates[{i}] {e.get('name', '?')}"
        errors += _check_entry(label, e, gset, vehicle)
        if e.get("name") in names:
            errors.append(f"{label}: name already used")
        if e.get("did") in dids:
            errors.append(
                f"{label}: DID 0x{e.get('did', 0):04X} already listed (polled or candidate)"
            )
        names.add(e.get("name"))
        dids.add(e.get("did"))
    # D-068: every scalar entry the CL250 may serve is polled, so the list may hold only the
    # entries the vehicle does not poll (D-078 item 2), or none.
    if not isinstance(cand.get("candidates"), list):
        errors.append("candidates: `candidates` must be a list (empty once all are polled)")
    errors += _check_identification(cand.get("identification"), vehicle, names, dids)
    return errors


def _field(f: dict[str, Any]) -> dict[str, Any]:
    """A field with its position spelled out: `size` bytes from `byte`, shifted by `bit`,
    `bits` wide (raw = (bytes >> bit) & (2^bits - 1), bytes big-endian unsigned)."""
    size = f.get("size", 1)
    return {
        "name": f["name"],
        "byte": f["byte"],
        "size": size,
        "bit": f.get("bit", 0),
        "bits": f.get("bits", 8 * size),
        "factor_num": f["factor_num"],
        "factor_den": f["factor_den"],
        "offset": f["offset"],
        "unit": f["unit"],
        "min": f["min"],
        "max": f["max"],
        "enum": {int(k): v for k, v in f["enum"].items()} if "enum" in f else None,
        "not_used_raw": f.get("not_used_raw"),
    }


def _entry(e: dict[str, Any]) -> dict[str, Any]:
    """A catalog entry as generated. A multi-value entry has no formula of its own: its
    scalar columns are the neutral raw view (factor 1/1, offset 0, unit "", 0..raw max)."""
    out = {k: e[k] for k in _BASE_REQUIRED}
    if "fields" in e:
        out |= {
            "factor_num": 1,
            "factor_den": 1,
            "offset": 0,
            "unit": "",
            "min": 0,
            "max": (1 << (8 * e["length"])) - 1,
            "fields": [_field(f) for f in e["fields"]],
        }
    else:
        out |= {k: e[k] for k in _SCALAR_KEYS} | {"fields": None}
    return out


def catalog(cand: dict[str, Any], vehicle: dict[str, Any]) -> list[dict[str, Any]]:
    """Merged catalog: polled DIDs first (table order), then unpolled entries by DID."""
    out: list[dict[str, Any]] = []
    for d in vehicle["dids"]:
        m = cand["polled"][d["name"]]
        out.append(
            {
                "did": d["did"],
                "obd_pid": d.get("obd_pid"),
                "name": d["name"],
                "label": m["label"],
                "group": m["group"],
                "length": d["length"],
                "factor_num": d["factor_num"],
                "factor_den": d["factor_den"],
                "offset": d["offset"],
                "unit": d["unit"],
                "min": d["min"],
                "max": d["max"],
                "fields": None,
                "description": d["description"],
                "status": STATUS_POLLED,
                "poll_period_ms": d["poll_period_ms"],
                "priority": d["priority"],
            }
        )
    for e in sorted(cand["candidates"], key=lambda e: e["did"]):
        out.append(
            {
                **_entry(e),
                "status": STATUS_CANDIDATE,
                "poll_period_ms": None,
                "priority": None,
            }
        )
    return out


def identification(cand: dict[str, Any]) -> list[dict[str, Any]]:
    """ISO 14229-1 identification DIDs by DID (ASCII, variable length, never polled)."""
    keys = ("did", "name", "label", "description", "encoding")
    return [{k: e[k] for k in keys} for e in sorted(cand["identification"], key=lambda e: e["did"])]


def _py(value: Any) -> str:
    return "None" if value is None else repr(value)


def generate_python(cand: dict[str, Any], vehicle: dict[str, Any], iso: dict[str, Any]) -> str:
    lines = [
        PY_BANNER,
        "",
        "# D-066, D-078 item 2. status 'polled' = in the tester's DID table; 'candidate' =",
        "# standard PID, not polled, support unknown until the D-059 discovery scan.",
        "# physical = raw * factor_num / factor_den + offset (raw unsigned big-endian).",
        "# A signal with `fields` (D-068) carries several values: decode it with",
        "# decode_fields(); its own factor_num/factor_den/offset/unit/min/max are the raw",
        "# view (1, 1, 0, '', 0, 2^(8*length)-1). A field is raw = (the `size` bytes from",
        "# `byte`, big-endian) >> `bit` & (2^`bits` - 1), then the same formula.",
        "",
    ]
    lines.append("GROUPS = (" + ", ".join(f'"{g}"' for g in cand["groups"]) + ",)")
    lines.append(f'STATUS_POLLED = "{STATUS_POLLED}"')
    lines.append(f'STATUS_CANDIDATE = "{STATUS_CANDIDATE}"')
    lines += ["", "SIGNALS = {"]
    keys = (
        "did",
        "obd_pid",
        "label",
        "group",
        "length",
        "factor_num",
        "factor_den",
        "offset",
        "unit",
        "min",
        "max",
        "fields",
        "status",
        "poll_period_ms",
        "priority",
        "description",
    )
    for e in catalog(cand, vehicle):
        body = ", ".join(f'"{k}": {_py(e[k])}' for k in keys)
        lines.append(f'    "{e["name"]}": {{{body}}},')
    lines += [
        "}",
        "",
        'BY_DID = {s["did"]: name for name, s in SIGNALS.items()}',
        "",
        "# ISO 14229-1 Annex C identification DIDs (ASCII, variable length), not polled.",
        "# 0xF18C (serial number) and 0xF190 (VIN) are personal data and not listed.",
        "IDENTIFICATION = {",
    ]
    ident = identification(cand)
    for i in ident:
        lines.append(
            f'    "{i["name"]}": {{"did": 0x{i["did"]:04X}, "label": {_py(i["label"])}, '
            f'"encoding": "{i["encoding"]}", "description": {_py(i["description"])}}},'
        )
    lines += [
        "}",
        "",
        'IDENTIFICATION_BY_DID = {i["did"]: name for name, i in IDENTIFICATION.items()}',
        "",
        "",
        "def decode(name: str, data: bytes) -> float:",
        '    """Physical value from the data bytes after the DID echo."""',
        "    s = SIGNALS[name]",
        '    if s["fields"] is not None:',
        '        raise ValueError(f"{name}: carries several values, use decode_fields()")',
        '    if len(data) < s["length"]:',
        "        raise ValueError(f\"{name}: need {s['length']} bytes\")",
        '    raw = int.from_bytes(data[: s["length"]], "big")',
        '    return raw * s["factor_num"] / s["factor_den"] + s["offset"]',
        "",
        "",
        "def decode_fields(name: str, data: bytes) -> dict[str, float | int | str | None]:",
        '    """Values of a multi-value signal from the data bytes after the DID echo.',
        "",
        "    An enum field gives its name (the raw value if the table does not list it), a",
        "    field whose raw value is not_used_raw gives None, a raw field (unit '') gives the",
        '    raw integer, any other field its physical value."""',
        "    s = SIGNALS[name]",
        '    if s["fields"] is None:',
        '        raise ValueError(f"{name}: a single value, use decode()")',
        '    if len(data) < s["length"]:',
        "        raise ValueError(f\"{name}: need {s['length']} bytes\")",
        "    out: dict[str, float | int | str | None] = {}",
        '    for f in s["fields"]:',
        '        chunk = data[f["byte"] : f["byte"] + f["size"]]',
        '        raw = (int.from_bytes(chunk, "big") >> f["bit"]) & ((1 << f["bits"]) - 1)',
        '        if raw == f["not_used_raw"]:',
        '            out[f["name"]] = None',
        '        elif f["enum"] is not None:',
        '            out[f["name"]] = f["enum"].get(raw, raw)',
        '        elif f["factor_num"] == f["factor_den"] and f["offset"] == 0:',
        '            out[f["name"]] = raw',
        "        else:",
        '            out[f["name"]] = raw * f["factor_num"] / f["factor_den"] + f["offset"]',
        "    return out",
        "",
        "",
        "def decode_ascii(data: bytes) -> str:",
        '    """Text of an identification DID answer (bytes after the DID echo), padding',
        '    (0x00, 0xFF, spaces) stripped; a byte outside ASCII becomes U+FFFD."""',
        '    return bytes(data).strip(b"\\x00\\xff ").decode("ascii", errors="replace")',
        "",
        "",
        *_dtc_record_python(iso),
    ]
    return "\n".join(lines)


def _dtc_record_python(iso: dict[str, Any]) -> list[str]:
    """D-090: host-side decoders of the 0x19 0x04 / 0x06 positive responses."""
    rep = iso["dtc_record_reports"]
    sid = next(s["sid"] for s in iso["services"] if s["name"] == "READ_DTC_INFORMATION")
    sid += iso["positive_response_offset"]
    sub = {s["name"]: s["id"] for s in iso["read_dtc_subfunctions"]}
    snap, ext = rep["snapshot"], rep["ext_data"]
    header = 2 + rep["dtc_and_status_length"]
    return [
        "# D-090: ReadDTCInformation 0x04 / 0x06 positive responses (ISO 14229-1:2013",
        "# Tables 274/276), decoded on the host only; the testers log them raw (D-080).",
        "# A snapshot identifier is decoded with this catalog. One it does not define with",
        "# a fixed length stops the walk: the bytes from that identifier on are returned",
        '# raw in "rest" and "stop" says why. Extended-data records have server-specific',
        "# lengths, so only the first record number is named.",
        f"DTC_SNAPSHOT_RESPONSE = (0x{sid:02X}, 0x{sub[snap['subfunction']]:02X})",
        f"DTC_EXT_DATA_RESPONSE = (0x{sid:02X}, 0x{sub[ext['subfunction']]:02X})",
        f"DTC_HEADER_LENGTH = {header}",
        f"DTC_SNAPSHOT_RECORD_HEADER_LENGTH = {snap['record_header_length']}",
        f"DTC_SNAPSHOT_IDENTIFIER_LENGTH = {snap['identifier_length']}",
        "DTC_SNAPSHOT_UNDEFINED_NUMBER_OF_IDENTIFIERS = "
        f"0x{snap['undefined_number_of_identifiers']:02X}",
        f"DTC_SNAPSHOT_LEGISLATED_RECORD = 0x{snap['legislated_record_number']:02X}",
        "DTC_EXT_DATA_MANUFACTURER_RECORDS = "
        f"(0x{ext['manufacturer_records'][0]:02X}, 0x{ext['manufacturer_records'][1]:02X})",
        "DTC_EXT_DATA_OBD_RECORDS = "
        f"(0x{ext['obd_records'][0]:02X}, 0x{ext['obd_records'][1]:02X})",
        'STOP_UNKNOWN_DID = "unknown_did"',
        'STOP_VARIABLE_LENGTH = "variable_length"',
        'STOP_TRUNCATED = "truncated"',
        "",
        "",
        "def _dtc_header(response: bytes, expected: tuple[int, int]) -> dict[str, object]:",
        "    if len(response) < DTC_HEADER_LENGTH or tuple(response[:2]) != expected:",
        '        raise ValueError("not a %02X %02X response with a DTC and its status" % expected)',
        '    return {"dtc": int.from_bytes(response[2:5], "big"), "status": response[5]}',
        "",
        "",
        "def decode_dtc_snapshot(response: bytes) -> dict[str, object]:",
        '    """A whole 0x59 0x04 response (from the SID on) as',
        '    {"dtc", "status", "records", "rest", "stop"}.',
        "",
        '    Each record is {"record_number", "number_of_identifiers", "values"}, each value',
        '    {"did", "name", "data", "value"} (value as decode() or decode_fields() give it).',
        '    "stop" is None when every byte was decoded, otherwise STOP_UNKNOWN_DID,',
        "    STOP_VARIABLE_LENGTH (an identification DID) or STOP_TRUNCATED, with the bytes",
        '    from that point in "rest"."""',
        "    out = _dtc_header(response, DTC_SNAPSHOT_RESPONSE)",
        "    records: list[dict[str, object]] = []",
        '    out.update(records=records, rest=b"", stop=None)',
        "    pos = DTC_HEADER_LENGTH",
        "    while pos < len(response):",
        "        if pos + DTC_SNAPSHOT_RECORD_HEADER_LENGTH > len(response):",
        "            out.update(rest=bytes(response[pos:]), stop=STOP_TRUNCATED)",
        "            return out",
        "        number, count = response[pos], response[pos + 1]",
        "        values: list[dict[str, object]] = []",
        '        records.append({"record_number": number, "number_of_identifiers": count,',
        '                        "values": values})',
        "        pos += DTC_SNAPSHOT_RECORD_HEADER_LENGTH",
        "        undefined = count == DTC_SNAPSHOT_UNDEFINED_NUMBER_OF_IDENTIFIERS",
        "        while (pos < len(response)) if undefined else (len(values) < count):",
        "            data_pos = pos + DTC_SNAPSHOT_IDENTIFIER_LENGTH",
        "            if data_pos > len(response):",
        "                out.update(rest=bytes(response[pos:]), stop=STOP_TRUNCATED)",
        "                return out",
        '            did = int.from_bytes(response[pos:data_pos], "big")',
        "            name = BY_DID.get(did)",
        "            if name is None:",
        "                ident = did in IDENTIFICATION_BY_DID",
        "                stop = STOP_VARIABLE_LENGTH if ident else STOP_UNKNOWN_DID",
        "                out.update(rest=bytes(response[pos:]), stop=stop)",
        "                return out",
        "            s = SIGNALS[name]",
        '            data = bytes(response[data_pos : data_pos + s["length"]])',
        '            if len(data) < s["length"]:',
        "                out.update(rest=bytes(response[pos:]), stop=STOP_TRUNCATED)",
        "                return out",
        '            scalar = s["fields"] is None',
        "            value = decode(name, data) if scalar else decode_fields(name, data)",
        '            values.append({"did": did, "name": name, "data": data, "value": value})',
        "            pos = data_pos + len(data)",
        "    return out",
        "",
        "",
        "def decode_dtc_ext_data(response: bytes) -> dict[str, object]:",
        '    """A whole 0x59 0x06 response as {"dtc", "status", "first_record_number",',
        '    "first_record_kind", "rest"}. The kind is "manufacturer", "obd", "reserved"',
        '    or None (no record); "rest" holds every byte after the DTC status, record',
        '    numbers included."""',
        "    out = _dtc_header(response, DTC_EXT_DATA_RESPONSE)",
        "    rest = bytes(response[DTC_HEADER_LENGTH:])",
        "    first = rest[0] if rest else None",
        "    lo, hi = DTC_EXT_DATA_MANUFACTURER_RECORDS",
        "    obd_lo, obd_hi = DTC_EXT_DATA_OBD_RECORDS",
        "    if first is None:",
        "        kind = None",
        "    elif lo <= first <= hi:",
        '        kind = "manufacturer"',
        "    elif obd_lo <= first <= obd_hi:",
        '        kind = "obd"',
        "    else:",
        '        kind = "reserved"',
        "    out.update(first_record_number=first, first_record_kind=kind, rest=rest)",
        "    return out",
        "",
    ]


def _dart_str(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$")
    return f"'{escaped}'"


def _dart_num(value: float | int) -> str:
    return repr(float(value)) if isinstance(value, float) else f"{value}.0"


def _camel(name: str) -> str:
    head, *rest = name.lower().split("_")
    return head + "".join(p.capitalize() for p in rest)


def _dart_fields(fields: list[dict[str, Any]] | None) -> list[str]:
    """The `fields:` argument of a multi-value VehicleSignal (none for a scalar one)."""
    if fields is None:
        return []
    out = ["    fields: <VehicleSignalField>["]
    for f in fields:
        out += [
            "      VehicleSignalField(",
            f"        name: {_dart_str(f['name'])},",
            f"        byte: {f['byte']},",
            f"        size: {f['size']},",
            f"        bit: {f['bit']},",
            f"        bits: {f['bits']},",
            f"        factorNum: {f['factor_num']},",
            f"        factorDen: {f['factor_den']},",
            f"        offset: {_dart_num(f['offset'])},",
            f"        unit: {_dart_str(f['unit'])},",
            f"        min: {_dart_num(f['min'])},",
            f"        max: {_dart_num(f['max'])},",
        ]
        if f["enum"] is not None:
            names = ", ".join(f"{k}: {_dart_str(v)}" for k, v in f["enum"].items())
            out.append(f"        enumNames: <int, String>{{{names}}},")
        if f["not_used_raw"] is not None:
            out.append(f"        notUsedRaw: {f['not_used_raw']},")
        out.append("      ),")
    return [*out, "    ],"]


