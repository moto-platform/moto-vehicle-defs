"""Vehicle signal catalog (D-066): polled DIDs + unpolled candidates, for host consumers.

`uds/vehicle_cl250_candidates.yaml` lists the standard SAE J1979 mode 0x01 PIDs the CL250
might serve over UDS 0x22 0xF4xx. They are not polled: no C target gets this catalog. It is
merged with the polled DIDs of `uds/vehicle_cl250.yaml` and generated as Python (vehicle-server)
and Dart (vehicle-mobile), so both can show every signal and mark which ones flow. A candidate
becomes a polled DID only through /signal-change (D-059 item 4, D-066 item 3).
"""

from __future__ import annotations

import re
from typing import Any

from .yaml_checks import frame_allowed, request_allowed, single_frame

SOURCE = "uds/vehicle_cl250.yaml + uds/vehicle_cl250_candidates.yaml"
PY_BANNER = f'"""GENERATED by vehicle-defs tools/codegen from {SOURCE}. DO NOT EDIT."""\n'
DART_BANNER = (
    f"// GENERATED by vehicle-defs tools/codegen from {SOURCE}. DO NOT EDIT.\n"
    "// Regenerate with `make gen`.\n"
)

_NAME = re.compile(r"[A-Z][A-Z0-9_]*")
_LENGTHS = (1, 2, 4)
_REQUIRED = (
    "obd_pid",
    "did",
    "name",
    "label",
    "group",
    "length",
    "factor_num",
    "factor_den",
    "offset",
    "unit",
    "min",
    "max",
    "description",
)
# Poll settings belong to uds/vehicle_cl250.yaml only: a candidate is never polled.
_POLL_KEYS = ("poll_period_ms", "stale_after_ms", "priority", "poll_period_verified")
STATUS_POLLED = "polled"
STATUS_CANDIDATE = "candidate"


def _is_int(value: Any) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _is_num(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _close(a: float, b: float) -> bool:
    return abs(a - b) <= 1e-9 * max(1.0, abs(a), abs(b))


def _check_entry(
    label: str, e: dict[str, Any], groups: set[str], vehicle: dict[str, Any]
) -> list[str]:
    errors: list[str] = []
    missing = [k for k in _REQUIRED if k not in e]
    if missing:
        return [f"{label}: missing {', '.join(missing)}"]
    for key in _POLL_KEYS:
        if key in e:
            errors.append(f"{label}: '{key}' not allowed, a candidate is never polled (D-066)")
    pid, did = e["obd_pid"], e["did"]
    if not (_is_int(pid) and 0x00 < pid <= 0xFF) or pid % 0x20 == 0:
        errors.append(f"{label}: obd_pid must be a data PID in 0x01..0xFF, not a support PID")
    elif did != 0xF400 | pid:
        errors.append(f"{label}: did must be 0xF400 | obd_pid = 0x{0xF400 | pid:04X}")
    if not (isinstance(e["name"], str) and _NAME.fullmatch(e["name"])):
        errors.append(f"{label}: name must be UPPER_SNAKE")
    if not (isinstance(e["label"], str) and e["label"].strip()):
        errors.append(f"{label}: empty label")
    if e["group"] not in groups:
        errors.append(f"{label}: group '{e['group']}' not in groups")
    if e["length"] not in _LENGTHS:
        errors.append(f"{label}: length must be one of {_LENGTHS}")
    num, den, off = e["factor_num"], e["factor_den"], e["offset"]
    if not (_is_int(num) and num > 0 and _is_int(den) and den > 0 and _is_num(off)):
        errors.append(f"{label}: factor_num/factor_den must be positive integers, offset a number")
    elif e["length"] in _LENGTHS and _is_num(e["min"]) and _is_num(e["max"]):
        raw_max = (1 << (8 * e["length"])) - 1
        if not _close(e["min"], off):
            errors.append(f"{label}: min {e['min']} != raw 0 through the formula ({off})")
        top = raw_max * num / den + off
        if not _close(e["max"], top):
            errors.append(f"{label}: max {e['max']} != raw {raw_max} through the formula ({top})")
    else:
        errors.append(f"{label}: min/max must be numbers")
    if not (isinstance(e["unit"], str) and e["unit"]):
        errors.append(f"{label}: empty unit")
    if _is_int(did) and 0 <= did <= 0xFFFF:
        payload = [0x22, did >> 8, did & 0xFF]
        if not request_allowed(vehicle["tester_policy"], payload):
            errors.append(f"{label}: 0x22 read refused by tester_policy (D-020)")
        elif not frame_allowed(vehicle, single_frame(vehicle, payload)):
            errors.append(f"{label}: 0x22 read refused by the frame gate (D-020)")
    return errors


def check_catalog(cand: dict[str, Any], vehicle: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    if cand.get("schema_version") != 1:
        errors.append("candidates: schema_version must be 1")
    groups = cand.get("groups")
    if not (isinstance(groups, list) and groups and len(set(groups)) == len(groups)):
        return errors + ["candidates: groups must be a non-empty list without duplicates"]
    gset = set(groups)
    polled_names = [d["name"] for d in vehicle["dids"]]
    polled_dids = {d["did"] for d in vehicle["dids"]}
    meta = cand.get("polled") or {}
    if set(meta) != set(polled_names):
        missing = sorted(set(polled_names) - set(meta))
        extra = sorted(set(meta) - set(polled_names))
        errors.append(
            "candidates: `polled` keys must equal the DID names of uds/vehicle_cl250.yaml "
            f"(missing {missing}, extra {extra})"
        )
    for name, m in meta.items():
        if (
            not isinstance(m, dict)
            or m.get("group") not in gset
            or not str(m.get("label", "")).strip()
        ):
            errors.append(f"candidates: polled {name} needs a known group and a label")
    names = set(polled_names)
    dids = set(polled_dids)
    for i, e in enumerate(cand.get("candidates") or []):
        label = f"candidates[{i}] {e.get('name', '?')}"
        errors += _check_entry(label, e, gset, vehicle)
        if e.get("name") in names:
            errors.append(f"{label}: name already used")
        if e.get("did") in dids:
            errors.append(
                f"{label}: DID 0x{e.get('did', 0):04X} already listed (polled or candidate)"
            )
        names.add(e.get("name"))
        dids.add(e.get("did"))
    # D-068: every scalar candidate is polled now, so the list may be empty; the file
    # stays for the multi-value PIDs that are not defined yet.
    if not isinstance(cand.get("candidates"), list):
        errors.append("candidates: `candidates` must be a list (empty once all are polled)")
    return errors


def catalog(cand: dict[str, Any], vehicle: dict[str, Any]) -> list[dict[str, Any]]:
    """Merged catalog: polled DIDs first (table order), then candidates by DID."""
    out: list[dict[str, Any]] = []
    for d in vehicle["dids"]:
        m = cand["polled"][d["name"]]
        out.append(
            {
                "did": d["did"],
                "obd_pid": d.get("obd_pid"),
                "name": d["name"],
                "label": m["label"],
                "group": m["group"],
                "length": d["length"],
                "factor_num": d["factor_num"],
                "factor_den": d["factor_den"],
                "offset": d["offset"],
                "unit": d["unit"],
                "min": d["min"],
                "max": d["max"],
                "description": d["description"],
                "status": STATUS_POLLED,
                "poll_period_ms": d["poll_period_ms"],
                "priority": d["priority"],
            }
        )
    for e in sorted(cand["candidates"], key=lambda e: e["did"]):
        out.append(
            {
                **{k: e[k] for k in _REQUIRED},
                "status": STATUS_CANDIDATE,
                "poll_period_ms": None,
                "priority": None,
            }
        )
    return out


def _py(value: Any) -> str:
    return "None" if value is None else repr(value)


def generate_python(cand: dict[str, Any], vehicle: dict[str, Any]) -> str:
    lines = [
        PY_BANNER,
        "",
        "# D-066. status 'polled' = in the tester's DID table; 'candidate' =",
        "# standard PID, not polled, support unknown until the D-059 discovery scan.",
        "# physical = raw * factor_num / factor_den + offset (raw unsigned big-endian).",
        "",
    ]
    lines.append("GROUPS = (" + ", ".join(f'"{g}"' for g in cand["groups"]) + ",)")
    lines.append(f'STATUS_POLLED = "{STATUS_POLLED}"')
    lines.append(f'STATUS_CANDIDATE = "{STATUS_CANDIDATE}"')
    lines += ["", "SIGNALS = {"]
    keys = (
        "did",
        "obd_pid",
        "label",
        "group",
        "length",
        "factor_num",
        "factor_den",
        "offset",
        "unit",
        "min",
        "max",
        "status",
        "poll_period_ms",
        "priority",
        "description",
    )
    for e in catalog(cand, vehicle):
        body = ", ".join(f'"{k}": {_py(e[k])}' for k in keys)
        lines.append(f'    "{e["name"]}": {{{body}}},')
    lines += [
        "}",
        "",
        'BY_DID = {s["did"]: name for name, s in SIGNALS.items()}',
        "",
        "",
        "def decode(name: str, data: bytes) -> float:",
        '    """Physical value from the data bytes after the DID echo."""',
        "    s = SIGNALS[name]",
        '    if len(data) < s["length"]:',
        "        raise ValueError(f\"{name}: need {s['length']} bytes\")",
        '    raw = int.from_bytes(data[: s["length"]], "big")',
        '    return raw * s["factor_num"] / s["factor_den"] + s["offset"]',
        "",
    ]
    return "\n".join(lines)


def _dart_str(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$")
    return f"'{escaped}'"


def _dart_num(value: float | int) -> str:
    return repr(float(value)) if isinstance(value, float) else f"{value}.0"


def _camel(name: str) -> str:
    head, *rest = name.lower().split("_")
    return head + "".join(p.capitalize() for p in rest)


def generate_dart(cand: dict[str, Any], vehicle: dict[str, Any]) -> str:
    out = [
        DART_BANNER,
        "/// Where a catalog signal stands (D-066).",
        "enum VehicleSignalStatus {",
        "  /// In the tester's DID table: polled and sent to the phone.",
        "  polled,",
        "",
        "  /// Standard PID, not polled; support unknown until the D-059 discovery scan.",
        "  candidate,",
        "}",
        "",
        "/// One vehicle signal: a polled CL250 DID or an unpolled candidate (D-066).",
        "///",
        "/// physical = raw * factorNum / factorDen + offset, raw unsigned big-endian.",
        "final class VehicleSignal {",
        "  const VehicleSignal({",
        "    required this.did,",
        "    required this.obdPid,",
        "    required this.name,",
        "    required this.label,",
        "    required this.group,",
        "    required this.length,",
        "    required this.factorNum,",
        "    required this.factorDen,",
        "    required this.offset,",
        "    required this.unit,",
        "    required this.min,",
        "    required this.max,",
        "    required this.status,",
        "    required this.pollPeriodMs,",
        "    required this.priority,",
        "    required this.description,",
        "  });",
        "",
        "  final int did;",
        "  final int? obdPid;",
        "  final String name;",
        "  final String label;",
        "  final String group;",
        "  final int length;",
        "  final int factorNum;",
        "  final int factorDen;",
        "  final double offset;",
        "  final String unit;",
        "  final double min;",
        "  final double max;",
        "  final VehicleSignalStatus status;",
        "  final int? pollPeriodMs;",
        "  final String? priority;",
        "  final String description;",
        "",
        "  bool get isPolled => status == VehicleSignalStatus.polled;",
        "",
        "  /// Physical value of a raw reading.",
        "  double physical(int raw) => raw * factorNum / factorDen + offset;",
        "}",
        "",
        "/// UI groups, in display order.",
        "const List<String> vehicleSignalGroups = <String>["
        + ", ".join(_dart_str(g) for g in cand["groups"])
        + "];",
        "",
        "/// Polled DIDs first (tester table order), then candidates by DID.",
        "const List<VehicleSignal> vehicleSignalCatalog = <VehicleSignal>[",
    ]
    for e in catalog(cand, vehicle):
        pid = "null" if e["obd_pid"] is None else f"0x{e['obd_pid']:02X}"
        poll = "null" if e["poll_period_ms"] is None else str(e["poll_period_ms"])
        prio = "null" if e["priority"] is None else _dart_str(e["priority"])
        out += [
            "  VehicleSignal(",
            f"    did: 0x{e['did']:04X},",
            f"    obdPid: {pid},",
            f"    name: {_dart_str(e['name'])},",
            f"    label: {_dart_str(e['label'])},",
            f"    group: {_dart_str(e['group'])},",
            f"    length: {e['length']},",
            f"    factorNum: {e['factor_num']},",
            f"    factorDen: {e['factor_den']},",
            f"    offset: {_dart_num(e['offset'])},",
            f"    unit: {_dart_str(e['unit'])},",
            f"    min: {_dart_num(e['min'])},",
            f"    max: {_dart_num(e['max'])},",
            f"    status: VehicleSignalStatus.{e['status']},",
            f"    pollPeriodMs: {poll},",
            f"    priority: {prio},",
            f"    description: {_dart_str(e['description'])},",
            "  ),",
        ]
    out += ["];", ""]
    out += ["/// Catalog signal names as constants.", "abstract final class VehicleSignalNames {"]
    for e in catalog(cand, vehicle):
        out.append(f"  static const String {_camel(e['name'])} = {_dart_str(e['name'])};")
    out += ["}", ""]
    return "\n".join(out)
